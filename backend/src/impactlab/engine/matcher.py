"""Price-time priority matching engine.

Pure Python, deterministic, integer paise prices, no I/O.
"""

from __future__ import annotations

from typing import Any

from impactlab.engine.book import OrderBook
from impactlab.engine.models import Event, Order, OrderType, Side, Status, Trade
from impactlab.engine.validation import validate_order


class MatchingEngine:
    """Matches incoming orders against a price-time priority OrderBook.

    Every state change appends an immutable Event to its event log.
    Deterministic when fed orders with consistent sequence timestamps.
    """

    __slots__ = (
        "book",
        "tick_size",
        "lot_size",
        "events",
        "trades",
        "_trade_id_seq",
        "_event_seq",
    )

    def __init__(
        self,
        book: OrderBook | None = None,
        tick_size: int = 5,
        lot_size: int = 1,
    ) -> None:
        self.book = book or OrderBook()
        self.tick_size = tick_size
        self.lot_size = lot_size
        self.events: list[Event] = []
        self.trades: list[Trade] = []
        self._trade_id_seq = 1
        self._event_seq = 1

    def _emit_event(self, ts: int, kind: str, payload: dict[str, Any]) -> Event:
        """Create and record a sequential event."""
        ev = Event(seq=self._event_seq, ts=ts, kind=kind, payload=payload)
        self._event_seq += 1
        self.events.append(ev)
        return ev

    def submit(self, order: Order) -> list[Trade]:
        """Submit an order to the matching engine.

        Follows price-time priority matching.
        Emits events for acceptance, trades, cancellations, or rejections.

        Args:
            order: Order to match or place.

        Returns:
            List of Trade objects generated by this order.
        """
        # 1. Validation
        is_valid, error_msg = validate_order(order, self.tick_size, self.lot_size)
        if not is_valid:
            order.status = Status.REJECTED
            self._emit_event(
                ts=order.ts,
                kind="REJECTED",
                payload={"order_id": order.id, "reason": error_msg or "Validation failed"},
            )
            return []

        # 2. Check POST_ONLY crossing
        if order.type == OrderType.POST_ONLY and order.price is not None:
            if order.side == Side.BUY:
                ba = self.book.best_ask
                if ba is not None and order.price >= ba:
                    order.status = Status.REJECTED
                    self._emit_event(
                        ts=order.ts,
                        kind="REJECTED",
                        payload={"order_id": order.id, "reason": "POST_ONLY would cross best ask"},
                    )
                    return []
            else:
                bb = self.book.best_bid
                if bb is not None and order.price <= bb:
                    order.status = Status.REJECTED
                    self._emit_event(
                        ts=order.ts,
                        kind="REJECTED",
                        payload={"order_id": order.id, "reason": "POST_ONLY would cross best bid"},
                    )
                    return []

        # 3. Check FOK fillability
        if order.type == OrderType.FOK:
            available = 0
            if order.side == Side.BUY:
                for price, queue in self.book.asks.items():
                    if order.price is not None and price > order.price:
                        break
                    available += sum(o.remaining for o in queue)
                    if available >= order.qty:
                        break
            else:
                for neg_price, queue in self.book.bids.items():
                    price = -neg_price
                    if order.price is not None and price < order.price:
                        break
                    available += sum(o.remaining for o in queue)
                    if available >= order.qty:
                        break

            if available < order.qty:
                order.status = Status.REJECTED
                self._emit_event(
                    ts=order.ts,
                    kind="REJECTED",
                    payload={"order_id": order.id, "reason": "FOK insufficient liquidity"},
                )
                return []

        # 4. Accepted
        self._emit_event(
            ts=order.ts,
            kind="ACCEPTED",
            payload={
                "order_id": order.id,
                "side": order.side.value,
                "type": order.type.value,
                "price": order.price,
                "qty": order.qty,
                "owner": order.owner,
            },
        )

        matched_trades: list[Trade] = []

        # 5. Execute matching
        if order.side == Side.BUY:
            while order.remaining > 0 and len(self.book.asks) > 0:
                best_ask_price = self.book.best_ask
                if best_ask_price is None:
                    break
                if (
                    order.type
                    in (OrderType.LIMIT, OrderType.IOC, OrderType.FOK, OrderType.POST_ONLY)
                    and order.price is not None
                    and order.price < best_ask_price
                ):
                    break

                level = self.book.asks[best_ask_price]
                maker = level[0]
                fill_qty = min(order.remaining, maker.remaining)

                trade = Trade(
                    id=self._trade_id_seq,
                    price=best_ask_price,
                    qty=fill_qty,
                    taker_order_id=order.id,
                    maker_order_id=maker.id,
                    taker_side=Side.BUY,
                    ts=order.ts,
                )
                self._trade_id_seq += 1
                matched_trades.append(trade)
                self.trades.append(trade)

                self._emit_event(
                    ts=order.ts,
                    kind="TRADE",
                    payload={
                        "trade_id": trade.id,
                        "price": trade.price,
                        "qty": trade.qty,
                        "taker_order_id": trade.taker_order_id,
                        "maker_order_id": trade.maker_order_id,
                        "taker_side": trade.taker_side.value,
                    },
                )

                maker.remaining -= fill_qty
                order.remaining -= fill_qty

                if maker.remaining == 0:
                    maker.status = Status.FILLED
                    level.popleft()
                    del self.book.orders_by_id[maker.id]
                    if not level:
                        del self.book.asks[best_ask_price]
                else:
                    maker.status = Status.PARTIAL
        else:
            # Sell taker matches against bids
            while order.remaining > 0 and len(self.book.bids) > 0:
                best_bid_price = self.book.best_bid
                if best_bid_price is None:
                    break
                if (
                    order.type
                    in (OrderType.LIMIT, OrderType.IOC, OrderType.FOK, OrderType.POST_ONLY)
                    and order.price is not None
                    and order.price > best_bid_price
                ):
                    break

                level = self.book.bids[-best_bid_price]
                maker = level[0]
                fill_qty = min(order.remaining, maker.remaining)

                trade = Trade(
                    id=self._trade_id_seq,
                    price=best_bid_price,
                    qty=fill_qty,
                    taker_order_id=order.id,
                    maker_order_id=maker.id,
                    taker_side=Side.SELL,
                    ts=order.ts,
                )
                self._trade_id_seq += 1
                matched_trades.append(trade)
                self.trades.append(trade)

                self._emit_event(
                    ts=order.ts,
                    kind="TRADE",
                    payload={
                        "trade_id": trade.id,
                        "price": trade.price,
                        "qty": trade.qty,
                        "taker_order_id": trade.taker_order_id,
                        "maker_order_id": trade.maker_order_id,
                        "taker_side": trade.taker_side.value,
                    },
                )

                maker.remaining -= fill_qty
                order.remaining -= fill_qty

                if maker.remaining == 0:
                    maker.status = Status.FILLED
                    level.popleft()
                    del self.book.orders_by_id[maker.id]
                    if not level:
                        del self.book.bids[-best_bid_price]
                else:
                    maker.status = Status.PARTIAL

        # 6. Post-match status & remainder handling
        if order.remaining == 0:
            order.status = Status.FILLED
        else:
            if order.type in (OrderType.LIMIT, OrderType.POST_ONLY):
                order.status = Status.PARTIAL if matched_trades else Status.NEW
                self.book.add_resting(order)
            else:
                # MARKET or IOC order remainder canceled
                canceled_qty = order.remaining
                order.remaining = 0
                order.status = Status.PARTIAL if matched_trades else Status.CANCELED
                self._emit_event(
                    ts=order.ts,
                    kind="CANCELED",
                    payload={"order_id": order.id, "canceled_qty": canceled_qty},
                )

        return matched_trades

    def cancel(self, order_id: int) -> Order | None:
        """Cancel a resting order in the book.

        Args:
            order_id: ID of the order to cancel.

        Returns:
            The canceled Order, or None if not found in book.
        """
        order = self.book.remove(order_id)
        if order is None:
            return None

        canceled_qty = order.remaining
        order.remaining = 0
        order.status = Status.CANCELED
        self._emit_event(
            ts=order.ts,
            kind="CANCELED",
            payload={"order_id": order.id, "canceled_qty": canceled_qty},
        )
        return order

    def modify(
        self,
        order_id: int,
        new_qty: int | None = None,
        new_price: int | None = None,
    ) -> Order | None:
        """Modify a resting order.

        Reducing quantity retains queue priority.
        Increasing quantity or changing price loses queue priority.

        Args:
            order_id: ID of the order to modify.
            new_qty: New remaining quantity (optional).
            new_price: New limit price in paise (optional).

        Returns:
            The modified Order, or None if not found.
        """
        order = self.book.get(order_id)
        if order is None:
            return None

        price_changed = new_price is not None and new_price != order.price
        qty_increased = new_qty is not None and new_qty > order.remaining

        if not price_changed and not qty_increased:
            # Simple in-place quantity reduction: keeps priority
            if new_qty is not None and new_qty > 0:
                order.remaining = new_qty
            self._emit_event(
                ts=order.ts,
                kind="MODIFIED",
                payload={
                    "order_id": order.id,
                    "new_qty": order.remaining,
                    "new_price": order.price,
                },
            )
            return order

        # Price changed or quantity increased -> remove and re-insert at end of queue
        self.book.remove(order_id)
        if new_qty is not None and new_qty > 0:
            order.remaining = new_qty
            order.qty = max(order.qty, new_qty)
        if new_price is not None and new_price > 0:
            order.price = new_price

        self.book.add_resting(order)
        self._emit_event(
            ts=order.ts,
            kind="MODIFIED",
            payload={
                "order_id": order.id,
                "new_qty": order.remaining,
                "new_price": order.price,
            },
        )
        return order

    def check_invariants(self) -> None:
        """Validate all engine and book invariants."""
        # Book invariants
        self.book.check_invariants()

        # Trade price on tick grid and positive qty
        for t in self.trades:
            assert t.qty > 0, f"Trade {t.id} has qty <= 0: {t.qty}"
            assert t.price > 0, f"Trade {t.id} has price <= 0: {t.price}"
            assert t.price % self.tick_size == 0, (
                f"Trade {t.id} price {t.price} not on tick grid {self.tick_size}"
            )

        # Event sequence strictly increasing with no gaps
        for i, ev in enumerate(self.events):
            assert ev.seq == i + 1, f"Event seq mismatch at index {i}: {ev.seq} != {i + 1}"
